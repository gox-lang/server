package deps

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const DepsGoFile = "deps.go"
const generatedMarker = "Code generated by gox dependency management. DO NOT EDIT."

// WriteDepsGo synchronizes the permanent Go dependency bridge used to make
// dependencies declared by GOX files visible to the Go toolchain.
func WriteDepsGo(root string, cfg GoxJSON, requiredImports ...string) error {
	imports := map[string]struct{}{}
	for _, path := range requiredImports {
		path = strings.TrimSpace(path)
		if path != "" {
			imports[path] = struct{}{}
		}
	}
	for path := range cfg.Dependencies {
		path = strings.TrimSpace(path)
		if path != "" {
			imports[path] = struct{}{}
		}
	}

	list := make([]string, 0, len(imports))
	for path := range imports {
		list = append(list, path)
	}
	sort.Strings(list)

	path := filepath.Join(root, DepsGoFile)
	if existing, err := os.ReadFile(path); err == nil {
		if !bytes.Contains(existing, []byte(generatedMarker)) {
			return fmt.Errorf("refusing to overwrite existing %s", DepsGoFile)
		}
	} else if !os.IsNotExist(err) {
		return err
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// %s\n\n", generatedMarker)
	b.WriteString("package main\n\n")
	if len(list) > 0 {
		b.WriteString("import (\n")
		for _, path := range list {
			fmt.Fprintf(&b, "\t_ %q\n", path)
		}
		b.WriteString(")\n")
	}
	return os.WriteFile(path, b.Bytes(), 0o644)
}
