package deps

import (
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

func TestPermanentRootDepsGoParticipatesInGoModTidy(t *testing.T) {
	root, goExec := newPermanentBridgeModule(t, map[string]string{
		"example.com/depone": "depone",
	})
	writePermanentBridge(t, root, "example.com/depone")

	runGo(t, goExec, root, "mod", "tidy")

	mod := readFile(t, filepath.Join(root, "go.mod"))
	if !strings.Contains(mod, "example.com/depone") {
		t.Fatalf("go.mod does not retain dependency imported only by deps.go:\n%s", mod)
	}
}

func TestPermanentRootDepsGoRemovalAllowsGoModTidyToRemoveDependency(t *testing.T) {
	root, goExec := newPermanentBridgeModule(t, map[string]string{
		"example.com/depone": "depone",
	})
	writePermanentBridge(t, root, "example.com/depone")
	runGo(t, goExec, root, "mod", "tidy")

	writePermanentBridge(t, root)
	runGo(t, goExec, root, "mod", "tidy")

	mod := readFile(t, filepath.Join(root, "go.mod"))
	if strings.Contains(mod, "require example.com/depone") || strings.Contains(mod, "example.com/depone v") {
		t.Fatalf("go.mod still requires dependency after it was removed from deps.go:\n%s", mod)
	}
}

func TestPermanentRootDepsGoSupportsMultipleDependencies(t *testing.T) {
	root, goExec := newPermanentBridgeModule(t, map[string]string{
		"example.com/depone": "depone",
		"example.com/deptwo": "deptwo",
	})
	writePermanentBridge(t, root, "example.com/depone", "example.com/deptwo")

	runGo(t, goExec, root, "mod", "tidy")

	mod := readFile(t, filepath.Join(root, "go.mod"))
	for _, module := range []string{"example.com/depone", "example.com/deptwo"} {
		if !strings.Contains(mod, module) {
			t.Fatalf("go.mod does not retain %s:\n%s", module, mod)
		}
	}
}

func TestPermanentRootDepsGoWorksWithGoListAndGoTest(t *testing.T) {
	root, goExec := newPermanentBridgeModule(t, map[string]string{
		"example.com/depone": "depone",
	})
	writePermanentBridge(t, root, "example.com/depone")
	runGo(t, goExec, root, "mod", "tidy")

	runGo(t, goExec, root, "list", "./...")
	runGo(t, goExec, root, "test", "./...")
}

func newPermanentBridgeModule(t *testing.T, modules map[string]string) (string, string) {
	t.Helper()
	goExec, err := exec.LookPath("go")
	if err != nil {
		t.Skip("go executable not available")
	}

	root := t.TempDir()
	var mod strings.Builder
	mod.WriteString("module example.com/app\n\ngo 1.20\n")
	for module, dir := range modules {
		depRoot := filepath.Join(root, dir)
		if err := os.MkdirAll(depRoot, 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(depRoot, "go.mod"), []byte("module "+module+"\n\ngo 1.20\n"), 0o644); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(depRoot, "dep.go"), []byte("package dep\n"), 0o644); err != nil {
			t.Fatal(err)
		}
		mod.WriteString("\nreplace " + module + " => ./" + dir + "\n")
	}
	if err := os.WriteFile(filepath.Join(root, "go.mod"), []byte(mod.String()), 0o644); err != nil {
		t.Fatal(err)
	}
	return root, goExec
}

func writePermanentBridge(t *testing.T, root string, imports ...string) {
	t.Helper()
	var src strings.Builder
	src.WriteString("// Code generated by GOX dependency management. DO NOT EDIT.\n\npackage main\n")
	if len(imports) != 0 {
		src.WriteString("\nimport (\n")
		for _, path := range imports {
			src.WriteString("\t_ \"")
			src.WriteString(path)
			src.WriteString("\"\n")
		}
		src.WriteString(")\n")
	}
	if err := os.WriteFile(filepath.Join(root, "deps.go"), []byte(src.String()), 0o644); err != nil {
		t.Fatal(err)
	}
}

func runGo(t *testing.T, goExec, root string, args ...string) {
	t.Helper()
	cmd := exec.Command(goExec, args...)
	cmd.Dir = root
	cmd.Env = append(os.Environ(), "GOWORK=off", "GOTOOLCHAIN=local")
	output, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("go %s failed: %v\n%s", strings.Join(args, " "), err, output)
	}
}

func readFile(t *testing.T, path string) string {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}
