package goxmap

import (
	"fmt"
	"strings"
)

// Writer builds transformed text and the map from that text to one immediate
// input document. It deliberately distinguishes copied bytes from generated
// scaffolding so callers cannot accidentally mark generated code as exact.
type Writer struct {
	generatedURI string
	sourceURI    string
	source       string
	output       strings.Builder
	mappings     []Mapping
}

// NewWriter creates a writer for one transformation stage.
func NewWriter(generatedURI, sourceURI, source string) (*Writer, error) {
	if generatedURI == "" {
		return nil, fmt.Errorf("generated URI cannot be empty")
	}
	if sourceURI == "" {
		return nil, fmt.Errorf("source URI cannot be empty")
	}
	return &Writer{generatedURI: generatedURI, sourceURI: sourceURI, source: source}, nil
}

// Len returns the current generated byte length.
func (w *Writer) Len() int {
	return w.output.Len()
}

// String returns the generated text written so far.
func (w *Writer) String() string {
	return w.output.String()
}

// WriteSource copies an exact source range into the generated document.
func (w *Writer) WriteSource(sourceRange Range) error {
	if !sourceRange.Valid() || sourceRange.End > len(w.source) {
		return fmt.Errorf("source range %v is outside source of length %d", sourceRange, len(w.source))
	}
	if sourceRange.Empty() {
		return nil
	}
	start := w.output.Len()
	w.output.WriteString(w.source[sourceRange.Start:sourceRange.End])
	w.appendMapping(Mapping{
		Generated: Range{Start: start, End: w.output.Len()},
		Original:  SourceRange{URI: w.sourceURI, Range: sourceRange},
		Kind:      Exact,
	})
	return nil
}

// WriteGenerated writes compiler-generated text anchored to a source range.
// Empty generated text is ignored; the anchor itself may be a point range.
func (w *Writer) WriteGenerated(text string, anchor Range) error {
	if !anchor.Valid() || anchor.End > len(w.source) {
		return fmt.Errorf("anchor range %v is outside source of length %d", anchor, len(w.source))
	}
	if text == "" {
		return nil
	}
	start := w.output.Len()
	w.output.WriteString(text)
	w.appendMapping(Mapping{
		Generated: Range{Start: start, End: w.output.Len()},
		Original:  SourceRange{URI: w.sourceURI, Range: anchor},
		Kind:      Anchor,
	})
	return nil
}

// Build returns the generated text and its validated immutable map.
func (w *Writer) Build() (string, *Map, error) {
	sourceMap, err := New(w.generatedURI, w.mappings)
	if err != nil {
		return "", nil, err
	}
	return w.output.String(), sourceMap, nil
}

func (w *Writer) appendMapping(mapping Mapping) {
	last := len(w.mappings) - 1
	if last >= 0 && w.mappings[last].Kind == Exact && mapping.Kind == Exact &&
		w.mappings[last].Generated.End == mapping.Generated.Start &&
		w.mappings[last].Original.URI == mapping.Original.URI &&
		w.mappings[last].Original.Range.End == mapping.Original.Range.Start {
		w.mappings[last].Generated.End = mapping.Generated.End
		w.mappings[last].Original.Range.End = mapping.Original.Range.End
		return
	}
	w.mappings = append(w.mappings, mapping)
}
